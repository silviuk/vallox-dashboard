// Generate the explicit section for a fixture: node tests/explicit.mjs fixture.json [name]
import fs from "node:fs"; import vm from "node:vm"; import path from "node:path";
import { fileURLToPath } from "node:url";
const dir = path.dirname(fileURLToPath(import.meta.url));
const window = { customElements: { get: (t) => t === "home-assistant" ? 1 : undefined, define() {} } };
vm.runInNewContext(fs.readFileSync(path.join(dir, "../dist/vallox-dashboard.js"), "utf8"), { window, HTMLElement: class {}, console: { info() {}, warn() {} }, setInterval, clearInterval });
const hass = { ...JSON.parse(fs.readFileSync(path.join(dir, process.argv[2]), "utf8")), locale: { language: (process.argv[4] !== "--yaml" && process.argv[4]) || "en" } };
const section = window.valloxDashboard.buildSection(hass, { name: process.argv[3] });
// Dependency-free YAML emitter for JSON-compatible card configs. Quote strings
// with JSON escaping (also valid YAML double-quoted scalars), including templates.
function yaml(value, indent = 0) {
  const pad = " ".repeat(indent);
  if (Array.isArray(value) && value.length) return value.map((x) => {
    const lines = yaml(x, indent + 2).split("\n");
    return `${pad}- ${lines[0].trimStart()}${lines.length > 1 ? `\n${lines.slice(1).join("\n")}` : ""}`;
  }).join("\n");
  if (value && typeof value === "object" && !Array.isArray(value) && Object.keys(value).length) {
    return Object.entries(value).map(([key, x]) => {
      const complex = x && typeof x === "object" && Object.keys(x).length;
      return complex ? `${pad}${key}:\n${yaml(x, indent + 2)}` : `${pad}${key}: ${JSON.stringify(x)}`;
    }).join("\n");
  }
  return pad + JSON.stringify(value);
}
if (process.argv.includes("--yaml")) {
  const integration = Object.values(hass.entities).find((e) => ["vallox2mqtt", "vallox"].includes(e.platform))?.platform;
  const description = integration === "vallox2mqtt" ? "vallox2mqtt (Vallox Digit SE / ValloPlus SE over RS485)" : "core Vallox integration (MV units)";
  process.stdout.write(`# Explicit section generated by vallox-dashboard ${window.valloxDashboard.version} for ${description}.\n# Paste it into a sections view (Edit dashboard > Raw configuration editor > under 'sections:')\n# and adjust the entity ids to your own. Only built-in cards are used.\n${yaml([section])}\n`);
} else process.stdout.write(JSON.stringify(section));
